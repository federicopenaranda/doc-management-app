import { ConfigService } from '@nestjs/config';
import type { NestExpressApplication } from '@nestjs/platform-express';
import {
  DocumentBuilder,
  SwaggerModule,
  type OpenAPIObject,
} from '@nestjs/swagger';
import type { Env } from './config/env.validation.js';

type PluginMetadata = Parameters<typeof SwaggerModule.loadPluginMetadata>[0];

/**
 * Swagger UI (/api) and the OpenAPI document (/api-json) exist only in local development.
 * Deployed environments (sandbox, prod) run NODE_ENV=production and serve neither.
 * Returns the document when it was registered, so the caller can write it to disk.
 */
export async function setupSwagger(
  app: NestExpressApplication,
): Promise<OpenAPIObject | undefined> {
  const nodeEnv = app
    .get<ConfigService<Env, true>>(ConfigService)
    .get('NODE_ENV');
  if (nodeEnv !== 'development') return undefined;

  // Metadata generated by `nest build` (SWC cannot run the plugin inline). It is not committed, so it is loaded
  // only if present; without it the docs just lack the plugin's extra detail. The `as string` keeps TypeScript
  // from requiring the file at compile time.
  const generated: { default: PluginMetadata } | undefined = await import(
    './metadata.js' as string
  ).catch(() => undefined);
  if (generated) await SwaggerModule.loadPluginMetadata(generated.default);
  const config = new DocumentBuilder()
    .setTitle('DMS API')
    .setVersion('0.1')
    .addBearerAuth()
    .build();
  const document = SwaggerModule.createDocument(app, config);
  SwaggerModule.setup('api', app, document);
  return document;
}
